# ---------------------------------------------------------------------------
# Number formatting
# ---------------------------------------------------------------------------

def pct(v, d: int = 1) -> str:
    return "n/a" if v is None or pd.isna(v) else f"{v:.{d}f}%"


def spct(v, d: int = 1) -> str:
    """Signed percent change, e.g. +8.8%."""
    return "n/a" if v is None or pd.isna(v) else f"{v:+.{d}f}%"


def pts(v, d: int = 1) -> str:
    return "n/a" if v is None or pd.isna(v) else f"{v:+.{d}f} pts"


def usd(v, d: int = 0) -> str:
    return "n/a" if v is None or pd.isna(v) else f"${v:,.{d}f}"


def usd_big(v) -> str:
    if v is None or pd.isna(v):
        return "n/a"
    v = float(v)
    if abs(v) >= 1e9:
        return f"${v / 1e9:.2f}B"
    if abs(v) >= 1e6:
        return f"${v / 1e6:.1f}M"
    if abs(v) >= 1e3:
        return f"${v / 1e3:.0f}K"
    return f"${v:,.0f}"


def num_big(v) -> str:
    if v is None or pd.isna(v):
        return "n/a"
    v = float(v)
    if abs(v) >= 1e6:
        return f"{v / 1e6:.2f}M"
    if abs(v) >= 1e3:
        return f"{v / 1e3:.0f}K"
    return f"{v:,.0f}"


def direction(v, up="up", down="down", flat="flat", tol: float = 0.05) -> str:
    if v is None or pd.isna(v):
        return flat
    return up if v > tol else down if v < -tol else flat


def mag(v, d: int = 1) -> str:
    """Unsigned percent for use after a direction word ("up 12.9%")."""
    return "n/a" if v is None or pd.isna(v) else f"{abs(v):.{d}f}%"


def updown(v, tol: float = 0.05) -> str:
    return direction(v, "up", "down", "flat", tol)


DAY_NAMES = {"Mon": "Monday", "Tue": "Tuesday", "Wed": "Wednesday", "Thu": "Thursday",
             "Fri": "Friday", "Sat": "Saturday", "Sun": "Sunday"}


def plural(n: int, word: str, many: str | None = None) -> str:
    return f"{n} {word if n == 1 else (many or word + 's')}"


def days_phrase(n: int) -> str:
    if n <= 0:
        return "today"
    if n == 1:
        return "tomorrow"
    return f"in {n} days"


def _clean_market(name: str) -> str:
    fixes = {"Phoenix -Prescott": "Phoenix", "San Francisco-Oak-San Jose": "San Francisco Bay Area",
             "Dallas-Ft. Worth": "Dallas-Fort Worth", "Portland- OR": "Portland, Ore.",
             "Sacramnto-Stkton-Modesto": "Sacramento", "Washington-DC -Hagrstwn": "Washington, D.C.",
             "Boston -Manchester": "Boston", "Seattle-Tacoma": "Seattle"}
    return fixes.get(name, name)


clean_market = _clean_market


