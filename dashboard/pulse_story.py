"""
pulse_story.py, the deterministic insight engine for the Dana Point PULSE board view.

Every section and every visual on the page carries a key question and a
written answer. The answers are computed here, from the same window-aware
figures the charts draw (see pulse_data.py), so they change with the data
window and never disagree with the tiles or charts beside them. Nothing is
generated by a language model on this path; the optional "Ask about this
section" buttons on the page are the only AI calls, and they are handed this
module's text as context so their answers stay consistent with the page.

Writing rules, from the Visit Dana Point voice and the project CLAUDE.md:
plain executive English, specific numbers with their comparison and period,
no em dashes, no exclamation marks, calibrated language for relationships
("moves with", never "drives"), and a named source on every claim.
"""

from __future__ import annotations

from dataclasses import dataclass, field

