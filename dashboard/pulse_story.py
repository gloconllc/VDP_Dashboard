def _miles_from_dana_point(coords: dict | None) -> dict:
    import math
    if not coords:
        return {}
    lat0, lon0 = math.radians(33.467), math.radians(-117.698)
    out = {}
    for k, (lat, lon) in coords.items():
        la, lo = math.radians(lat), math.radians(lon)
        a = math.sin((la - lat0) / 2) ** 2 + math.cos(lat0) * math.cos(la) * math.sin((lo - lon0) / 2) ** 2
        out[k] = 3958.8 * 2 * math.asin(math.sqrt(a))
    return out


def build_model(conn, months: float, start_iso: str | None, end_iso: str | None, label: str,
                dma_coords: dict | None = None) -> Model | None:
    daily = pdx.hotel_daily(conn)
    if daily is None or daily.empty:
        return None
    monthly = pdx.hotel_monthly(conn)
    w = pdx.resolve_window(daily["date"].max(), months, start_iso, end_iso, label)
    dow = pdx.day_of_week(daily, w)
    dm = pdx.datafy_monthly(conn)
    markets = pdx.datafy_markets(conn)
    ads = pdx.advertising(conn)
    m = Model(
        window=w, daily=daily, monthly=monthly,
        hotel=pdx.hotel_window(daily, monthly, w),
        trend=pdx.hotel_trend(daily, monthly, w),
        dow=dow, wk=pdx.weekend_gap(dow),
        compression=pdx.compression_by_quarter(daily, 8),
        momentum=pdx.momentum(daily),
        peers=pdx.peer_window(pdx.peer_weekly(conn), w),
        bench=pdx.benchmark_ytd(conn, daily),
        multiyear=pdx.costar_multiyear(conn),
        segments=pdx.costar_segments(conn, w),
        dfy_monthly=dm, dfy=pdx.datafy_window(dm, w), dfy_trend=pdx.datafy_trend(dm, w),
        link=pdx.hotel_vs_visitor_spend(monthly, dm),
        markets=markets, categories=pdx.datafy_categories(conn), profile=pdx.datafy_profile(conn),
        ads=ads, ad_mix=pdx.ad_vs_spend_markets(ads, markets),
        events=pdx.event_last_year(daily, pdx.upcoming_events(conn)),
        group=pdx.group_mix_latest(conn), insight=pdx.forward_insight(conn),
        fresh=pdx.freshness(conn),
        miles=_miles_from_dana_point(dma_coords),
    )
    m.text = write_all(m)
    return m


